/**
 * ハーネスのメモリ上のシートへ架空データを入れる。
 * 時限は本番と同じ並び（Setup.js の MOVE_PERIOD_ROWS_）で作る。
 */
function seed(h) {
  h.reset();
  h.value('MOVE_PERIOD_ROWS_()').forEach(function (r) {
    h.add('periods', { period: r[0], start_time: r[1], end_time: r[2], support_types: r[3], label: r[4] });
  });
  h.add('terms', { term_id: TERM, system: 'semester', start_date: '2026-09-21', end_date: '2027-01-30' });

  STAFFS.forEach(function (s, i) {
    h.add('staffs', {
      staff_id: s[0], name: s[1], role: s[2], skills: s[3],
      available_slots: s[4], assist_slots: s[5],
    });
    h.add('contacts', {
      staff_id: s[0], name: s[1], email: s[0].toLowerCase() + '@example.jp',
      // 090-0000-xxxx は架空と分かる並び（実在の番号に当たらないよう 0000 を入れる）
      phone: '090-0000-' + String(1001 + i),
      webhook_url: 'https://chat.googleapis.com/v1/spaces/DEMO' + i + '/messages?key=k&token=t',
    });
  });
  COURSES.forEach(function (c) {
    h.add('courses', {
      course_id: c[0], quarter: TERM, day: c[1], period: c[2], support_type: c[3],
      user_student: c[4], subject: c[5], room: c[6], staff_a_id: c[7], staff_b_id: c[8], note: c[9],
      instructor: c[5] ? '担当 教員' : '',
    });
  });
  VACANCIES.forEach(function (v) {
    h.add('vacancies', {
      vacancy_id: v[0], date: WEEK[v[1]], course_id: v[2], absent_staff_id: v[3],
      result: v[4], substitute_staff_id: v[5], group_id: v[6], notify_status: '送信済',
    });
  });
  RESPONSES.forEach(function (r) {
    h.add('responses', { vacancy_id: r[0], staff_id: r[1], answer: r[2], answered_at: '2026-11-09 21:10:00' });
  });
}

